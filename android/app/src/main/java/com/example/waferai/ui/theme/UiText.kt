internal val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.CHINESE }
internal val LocalEnglish = staticCompositionLocalOf { false }

@Composable
internal fun UiText(
    text: String, modifier: Modifier = Modifier, color: Color = Color.Unspecified,
    fontFamily: FontFamily? = null, overflow: TextOverflow = TextOverflow.Clip,
    maxLines: Int = Int.MAX_VALUE, minLines: Int = 1, style: TextStyle = LocalTextStyle.current
) {
    val language = LocalAppLanguage.current
    val translated = localizedCore(text, language) ?: if (language.chinese) text else englishText(text)
    Text(translated, modifier, color, fontFamily = fontFamily,
        overflow = overflow, maxLines = maxLines, minLines = minLines, style = style)
}

internal fun englishText(text: String): String {
    englishLabels[text]?.let { return it }
    for ((pattern, translation) in formattedLabels) {
        if (pattern.matches(text)) return pattern.replace(text, translation)
    }
    return text
}

