"""Convert the reviewed wafertools WM-811K fixture into offline demonstration assets.

The pinned fixture is display material, not a new evaluation or training set.
Coordinates are inverted back to the original WM-811K matrix without resizing.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import struct
import urllib.request

COMMIT = "79f0c202f162c1c62fc3d027f6a88aef8b62ffe0"
URL = f"https://raw.githubusercontent.com/wafertools/wafermap/{COMMIT}/docs/examples/wm811k-sample.json"
SHA256 = "fec21cd1fadea982a8171b6c6a74c3b86cc7179dedc87fd0ed80211d172a2b7d"
SOURCE = "https://wafertools.github.io/wafermap/examples/real-data.html"
CATEGORIES = [
    ("Center", "CENTER", "中心型"), ("Donut", "DONUT", "环带型"),
    ("Edge-Loc", "EDGE_LOCAL", "边缘局部型"), ("Edge-Ring", "EDGE_RING", "边缘环形"),
    ("Loc", "LOCAL", "局部聚集型"), ("Near-full", "NEAR_FULL", "近全失效型"),
    ("Random", "RANDOM", "随机型"), ("Scratch", "SCRATCH", "划痕型"),
    ("none", "NONE", "无特定缺陷模式")]


def convert(raw):
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError("Fixture differs from the reviewed source; review before updating.")
    samples = json.loads(raw)
    assert Counter(s["failureType"] for s in samples) == {label: 3 for label, _, _ in CATEGORIES}
    counts = Counter()
    converted = []
    for sample in samples:
        label = sample["failureType"]
        _, category, title = next(c for c in CATEGORIES if c[0] == label)
        counts[label] += 1
        number = counts[label]
        rows, cols = sample["gridRows"], sample["gridCols"]
        assert 1 <= rows <= 512 and 1 <= cols <= 512
        grid = [[0] * cols for _ in range(rows)]
        seen = set()
        for die in sample["results"]:
            r, c = die["y"] + rows // 2, die["x"] + cols // 2
            assert isinstance(r, int) and isinstance(c, int)
            assert 0 <= r < rows and 0 <= c < cols and (r, c) not in seen
            assert die["hbin"] in (1, 2)
            seen.add((r, c)); grid[r][c] = die["hbin"]
        flat = bytes(v for row in grid for v in row)
        good, bad = flat.count(1), flat.count(2)
        assert good + bad > 0
        name = f"wm811k-real-{label.lower()}-{number:02d}.json"
        document = {"lot_code": "WM811K-" + sample["lotName"], "wafer_code": "W" + str(sample["waferIndex"]), "map": grid}
        payload = json.dumps(document, separators=(",", ":")).encode()
        metadata = {"file": name, "label": label, "category": category, "title": f"{title} {number:02d}",
            "lot_code": document["lot_code"], "wafer_code": document["wafer_code"],
            "rows": rows, "cols": cols, "good": good, "bad": bad,
            "matrix_sha256": hashlib.sha256(struct.pack(">II", rows, cols) + flat).hexdigest(),
            "asset_sha256": hashlib.sha256(payload).hexdigest()}
        converted.append((metadata, payload))
    return converted


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", type=Path, help="Use a local copy; its SHA-256 must match.")
    args = parser.parse_args()
    raw = args.fixture.read_bytes() if args.fixture else urllib.request.urlopen(URL, timeout=30).read()
    entries = convert(raw)
    root = Path(__file__).resolve().parents[1]
    assets = root / "android/app/src/main/assets/samples"
    for metadata, payload in entries:
        (assets / metadata["file"]).write_bytes(payload)
    manifest = {"source_page": SOURCE, "fixture_url": URL, "fixture_sha256": SHA256,
        "upstream_commit": COMMIT, "dataset": "WM-811K", "sample_count": len(entries),
        "category_count": 9, "coordinate_rule": "row=y+gridRows//2; col=x+gridCols//2; missing=0",
        "purpose": "Offline demonstration only; original annotations are not model predictions.",
        "samples": [m for m, _ in entries]}
    (assets / "wafertools-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    lines = ["package com.example.waferai.data.local", "", "// Real sample entries are generated by scripts/import_wafertools_samples.py.",
        "enum class DemoCategory(val title: String) {", "    SYNTHETIC(\"人工演示\"),"]
    lines += [f'    {code}("{title}")' + (";" if i == len(CATEGORIES)-1 else ",") for i, (_, code, title) in enumerate(CATEGORIES)]
    lines += ["}", "", "enum class DemoWafer(",
        "    val filename: String, val title: String, val description: String,",
        "    val category: DemoCategory = DemoCategory.SYNTHETIC, val datasetLabel: String? = null,",
        "    val lotCode: String = \"\", val waferCode: String = \"\",",
        "    val rows: Int = 0, val cols: Int = 0, val goodCount: Int = 0, val badCount: Int = 0",
        ") {",
        '    GENERAL("demo-wafer-001.json", "基础晶圆", "适合练习导入、点选和良率计算。"),',
        '    EDGE_RING("demo-wafer-edge-ring.json", "边缘环状", "缺陷沿外圈分布，可查看边缘分区。"),',
        '    SCRATCH("demo-wafer-scratch.json", "划痕状", "缺陷沿斜线分布，可放大查看单颗芯片。"),']
    for i, (m, _) in enumerate(entries):
        number = i % 3 + 1
        pct = m["good"] / (m["good"] + m["bad"]) * 100
        detail = f'{m["lot_code"]} / {m["wafer_code"]} · {m["rows"]}×{m["cols"]} · 良率 {pct:.2f}%'
        values = [m["file"], m["title"], detail]
        strings = ", ".join(json.dumps(v, ensure_ascii=False) for v in values)
        lines.append(f'    WM_{m["category"]}_{number}({strings}, DemoCategory.{m["category"]}, "{m["label"]}", "{m["lot_code"]}", "{m["wafer_code"]}", {m["rows"]}, {m["cols"]}, {m["good"]}, {m["bad"]})' + (";" if i == len(entries)-1 else ","))
    lines += ["", "    val isReal get() = datasetLabel != null", "", "    companion object {",
        f'        const val SourcePage = "{SOURCE}"',
        "        fun search(query: String, category: DemoCategory? = null): List<DemoWafer> {",
        "            val text = query.trim().lowercase(java.util.Locale.ROOT)",
        "            return entries.filter { sample ->",
        "                (category == null || sample.category == category) &&",
        '                    (text.isBlank() || listOf(sample.title, sample.description, sample.category.title,',
        '                        sample.datasetLabel.orEmpty(), if (sample.isReal) "真实 wm-811k wafertools" else "人工 演示 synthetic")',
        '                        .any { text in it.lowercase(java.util.Locale.ROOT) })',
        "            }.sortedBy { if (it.isReal) 0 else 1 }", "        }", "    }", "}", ""]
    kotlin = "\n".join(lines).replace('\\\"', '\"')
    (root / "android/app/src/main/java/com/example/waferai/data/local/DemoWafer.kt").write_text(kotlin, encoding="utf-8")
    print(json.dumps({"samples": len(entries), "classes": 9, "unique_inputs": len({m['matrix_sha256'] for m, _ in entries}), "asset_bytes": sum(len(b) for _, b in entries)}))


if __name__ == "__main__":
    main()
